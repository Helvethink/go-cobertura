package main

import (
	"regexp"
	"testing"
)

func TestIgnore(t *testing.T) {
	tests := []struct {
		name          string
		fileName      string
		contents      string
		dirsExpected  bool
		filesExpected bool
		genExpected   bool
	}{
		{
			name:         "matching directory",
			fileName:     "foo/bar/zip.go",
			contents:     "blah blah...",
			dirsExpected: true,
		},
		{
			name:         "matching parent directory",
			fileName:     "foo/bar/zip/test.go",
			contents:     "blah blah...",
			dirsExpected: true,
		},
		{
			name:         "matching Windows directory",
			fileName:     `foo\bar\zip.go`,
			contents:     "blah blah...",
			dirsExpected: true,
		},
		{
			name:          "matching file",
			fileName:      "zip/foobar/gen.go",
			contents:      "blah blah...",
			filesExpected: true,
		},
		{
			name:     "canonical generated marker",
			fileName: "foobar/test.go",
			contents: `// Code generated by zzz; DO NOT EDIT.
package test`,
			genExpected: true,
		},
		{
			name:     "generated marker after long license header",
			fileName: "foobar/test.go",
			contents: `// Copyright 2026 Example Authors.
// This license header deliberately extends beyond the old detection limit.
// This license header deliberately extends beyond the old detection limit.
// This license header deliberately extends beyond the old detection limit.
// This license header deliberately extends beyond the old detection limit.
// This license header deliberately extends beyond the old detection limit.
// Code generated by zzz; DO NOT EDIT.
package test`,
			genExpected: true,
		},
		{
			name:     "marker after package clause",
			fileName: "foobar/test.go",
			contents: `package test
// Code generated by zzz; DO NOT EDIT.`,
		},
		{
			name:     "noncanonical autogenerated marker",
			fileName: "foobar/test.go",
			contents: `// AUTOGENERATED FILE: zzz stub code to make the package
package test`,
		},
		{
			name:     "generated marker missing do not edit suffix",
			fileName: "foobar/test.go",
			contents: `// Code generated by zzz v1.0.0
package test`,
		},
		{
			name:     "marker inside string literal",
			fileName: "foobar/test.go",
			contents: `package test

const notice = "// Code generated by zzz; DO NOT EDIT."`,
		},
	}

	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			contents := []byte(test.contents)
			empty := Ignore{}
			dirs := Ignore{Dirs: regexp.MustCompile(`/bar$`)}
			files := Ignore{Files: regexp.MustCompile(`bar/gen\.go$`)}
			generated := Ignore{GeneratedFiles: true}

			if empty.Match(test.fileName, nil) || empty.Match(test.fileName, contents) {
				t.Errorf("empty ignore configuration matched %q", test.fileName)
			}
			if got := dirs.Match(test.fileName, nil); got != test.dirsExpected {
				t.Errorf("directory match without contents = %t, want %t", got, test.dirsExpected)
			}
			if got := files.Match(test.fileName, nil); got != test.filesExpected {
				t.Errorf("file match without contents = %t, want %t", got, test.filesExpected)
			}
			if generated.Match(test.fileName, nil) {
				t.Errorf("generated-file matching succeeded without contents")
			}
			if got := generated.Match(test.fileName, contents); got != test.genExpected {
				t.Errorf("generated-file match = %t, want %t", got, test.genExpected)
			}
		})
	}
}
